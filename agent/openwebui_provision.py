def build_tool_content() -> str:
    """Source for the Open WebUI tool: thin methods that call agent/tools.py."""
    parts = [_TOOL_HEADER]
    for function in TOOL_FUNCTIONS:
        signature = inspect.signature(function)
        params = ", ".join(
            ["self"]
            + [
                f"{name}: {param.annotation}"
                + ("" if param.default is param.empty else f" = {param.default!r}")
                for name, param in signature.parameters.items()
            ]
        )
        doc = "\n".join(
            f"        {line}".rstrip() for line in inspect.getdoc(function).splitlines()
        )
        call = ", ".join(signature.parameters)
        parts.append(
            f"    def {function.__name__}({params}) -> str:\n"
            f'        """\n{doc}\n        """\n'
            f"        return _tools.{function.__name__}({call})\n\n"
        )
    return "".join(parts).rstrip() + "\n"


def skill_payloads() -> list[dict]:
    """One Open WebUI skill per agent/skills/<name>/SKILL.md (same file Strands loads)."""
    payloads = []
    for skill_dir in sorted(SKILLS_DIR.iterdir()):
        content = (skill_dir / "SKILL.md").read_text()
        description = re.search(r"^description:\s*(.+)$", content, re.MULTILINE).group(
            1
        )
        payloads.append(
            {
                "id": skill_dir.name,
                "name": skill_dir.name,
                "description": description.strip(),
                "content": content,
            }
        )
    return payloads


def model_payload(base_model_id: str, skill_ids: list[str]) -> dict:
    """The agent as an Open WebUI model. Only the system prompt and reasoning effort are set."""
    effort = settings.reasoning_effort()
    return {
        "id": MODEL_ID,
        "name": MODEL_NAME,
        "base_model_id": base_model_id,
        "meta": {
            "description": "FDA inspections, citations and recalls, with the work shown.",
            "toolIds": [TOOL_ID],
            "suggestion_prompts": SUGGESTED_PROMPTS,
            "skillIds": skill_ids,
            # Off: Open WebUI's own tools (time, memory, knowledge, skills loader, ...).
            "capabilities": {"builtin_tools": False},
        },
        "params": {
            "system": SYSTEM_PROMPT_PATH.read_text(),
            **({"reasoning_effort": effort} if effort else {}),
        },
        "is_active": True,
    }


class OpenWebUI:
    """The few Open WebUI API calls this script needs."""

    def __init__(self, base_url: str) -> None:
        self.base_url = base_url.rstrip("/")
        self.token = ""

    def request(
        self, method: str, path: str, body: dict | None = None
    ) -> dict | list | None:
        request = urllib.request.Request(
            f"{self.base_url}{path}",
            method=method,
            data=json.dumps(body).encode() if body is not None else None,
            headers={
                "Content-Type": "application/json",
                **({"Authorization": f"Bearer {self.token}"} if self.token else {}),
            },
        )
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                return json.loads(response.read() or "null")
        except urllib.error.HTTPError as error:
            raise RuntimeError(
                f"{method} {path} -> {error.code}: {error.read().decode()[:300]}"
            ) from error

    def sign_in(self, email: str, password: str) -> None:
        reply = self.request(
            "POST", "/api/v1/auths/signin", {"email": email, "password": password}
        )
        self.token = reply["token"]

    def upsert(self, kind: str, item_id: str, payload: dict) -> str:
        """Create the item, or update it if it exists. `kind` is 'tools' or 'skills'."""
        try:
            self.request("GET", f"/api/v1/{kind}/id/{item_id}")
        except RuntimeError:
            self.request("POST", f"/api/v1/{kind}/create", payload)
            return "created"
        self.request("POST", f"/api/v1/{kind}/id/{item_id}/update", payload)
        return "updated"

    def upsert_model(self, payload: dict) -> str:
        existing = self.request("GET", "/api/v1/models/list?query=&page=1") or {}
        known = {item["id"] for item in existing.get("items", [])}
        if payload["id"] in known:
            self.request("POST", "/api/v1/models/model/update", payload)
            return "updated"
        self.request("POST", "/api/v1/models/create", payload)
        return "created"


def provision(client: OpenWebUI, base_model_id: str) -> dict[str, str]:
    outcome = {}
    tool_content = build_tool_content()
    outcome["tool"] = client.upsert(
        "tools",
        TOOL_ID,
        {
            "id": TOOL_ID,
            "name": "Glass Box FDA tools",
            "content": tool_content,
            "meta": {"description": "run_query, create_plan, complete_step"},
        },
    )
    skills = skill_payloads()
    for skill in skills:
        outcome[f"skill {skill['id']}"] = client.upsert("skills", skill["id"], skill)
    outcome["model"] = client.upsert_model(
        model_payload(base_model_id, [s["id"] for s in skills])
    )
    return outcome


def main() -> None:
    client = OpenWebUI(os.environ.get("OPENWEBUI_URL", "http://openwebui:8080"))
    client.sign_in(os.environ["WEBUI_ADMIN_EMAIL"], os.environ["WEBUI_ADMIN_PASSWORD"])
    for what, result in provision(client, os.environ["LLM_MODEL_ID"]).items():
        print(f"{result:>8}  {what}")
    print(f"\nIn Open WebUI (http://localhost:3000), pick the '{MODEL_NAME}' model.")


if __name__ == "__main__":
    main()
