"""Configure Open WebUI from agent/, so both runtimes run the same agent.

Run it after the stack is up (idempotent; safe to rerun after editing agent/):

    docker compose exec jupyter python -m agent.openwebui_provision

It creates or updates, over Open WebUI's API:
  - one tool that delegates to agent/tools.py (the containers share that file),
  - one skill per agent/skills/<name>/SKILL.md,
  - a model, "Glass Box FDA", with the system prompt, the tool and the skills attached.

Open WebUI's own built-in tools are switched off for that model, so the model sees
the three tools and nothing else. Its skills are injected in full, where Strands lets
the model load them on demand: the skill text is identical.
"""

from __future__ import annotations

import inspect
import json
import os
import re
import urllib.error
import urllib.request

from agent import settings, tools
from agent.strands_agent import SKILLS_DIR, SYSTEM_PROMPT_PATH

TOOL_ID = "glassbox_fda"
MODEL_ID = "glassbox-fda"
MODEL_NAME = "Glass Box FDA"
TOOL_FUNCTIONS = (tools.run_query, tools.create_plan, tools.complete_step)

# Shown on a new chat. Each is the exact text of a benchmark question in tests/questions.yaml
# (q008, q010, q017), so every demo prompt is regression-tested: a breakdown, a multi-step
# question across datasets, and one the data cannot answer.
SUGGESTED_PROMPTS = [
    {
        "title": ["Recalls by class", "how many in each class?"],
        "content": "For fiscal year 2024, how many recall events were there in each recall class?",
    },
    {
        "title": ["Recalls and inspections", "firms in both"],
        "content": (
            "How many firms (by FEI) had a Class I recall event classified in fiscal year 2025 "
            "and also had an OAI inspection result in fiscal year 2025?"
        ),
    },
    {
        "title": ["Warning letters", "what the data can't tell you"],
        "content": (
            "How many warning letters did the FDA issue to drug manufacturers in fiscal year 2025?"
        ),
    },
]

